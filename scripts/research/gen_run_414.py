def get_relocs_and_calls():
    raw = EXE.read_bytes()
    e_lfanew = struct.unpack_from('<I', raw, 0x3c)[0]
    nt_hdr = e_lfanew
    opt_hdr = nt_hdr + 24
    image_base = struct.unpack_from('<I', raw, opt_hdr + 28)[0]
    rva_reloc = struct.unpack_from('<I', raw, opt_hdr + 136)[0]
    size_reloc = struct.unpack_from('<I', raw, opt_hdr + 140)[0]

    num_sections = struct.unpack_from('<H', raw, nt_hdr + 6)[0]
    sec_hdr_start = opt_hdr + struct.unpack_from('<H', raw, nt_hdr + 20)[0]
    sections = []
    for i in range(num_sections):
        sec = raw[sec_hdr_start + i*40 : sec_hdr_start + (i+1)*40]
        name = sec[:8].rstrip(b'\x00').decode('latin1')
        vsize, vrva, rsize, rraw = struct.unpack_from('<IIII', sec, 8)
        sections.append((name, vrva, vsize, rraw, rsize))

    def rva_to_raw(rva):
        for name, vrva, vsize, rraw, rsize in sections:
            if vrva <= rva < vrva + max(vsize, rsize):
                return rraw + (rva - vrva)
        return None

    relocs = []
    cur_raw = rva_to_raw(rva_reloc)
    end_raw = cur_raw + size_reloc
    while cur_raw < end_raw:
        page_rva, block_size = struct.unpack_from('<II', raw, cur_raw)
        if block_size == 0:
            break
        count = (block_size - 8) // 2
        for j in range(count):
            entry = struct.unpack_from('<H', raw, cur_raw + 8 + j*2)[0]
            if (entry >> 12) == 3: # HIGHLOW
                va = image_base + page_rva + (entry & 0xfff)
                if START_VA <= va < END_VA:
                    file_off = rva_to_raw(page_rva + (entry & 0xfff))
                    target = struct.unpack_from('<I', raw, file_off)[0]
                    relocs.append((va - START_VA, target))
        cur_raw += block_size

    # Direct calls from disassembly.asm
    calls = []
    lines = ASM.read_text(encoding='latin1').splitlines()
    in_func = False
    for line in lines:
        if line.startswith('; FUNCTION 004d3420'):
            in_func = True
            continue
        if in_func and line.startswith('; FUNCTION'):
            break
        if in_func:
            m = re.match(r'^(00[0-9a-f]{6})\s+[0-9a-f]+\s+CALL (0x00[0-9a-f]{6})', line)
            if m:
                va = int(m.group(1), 16)
                tgt = int(m.group(2), 16)
                calls.append((va - START_VA, tgt))

    # Determine ret byte pop for each unique call
    unique_calls = sorted(set(t for _, t in calls))
    target_vas = [f'{t:08x}' for t in unique_calls]
    fn_rets = {}
    for i, l in enumerate(lines):
        m = re.match(r'^;\s*FUNCTION\s+([0-9a-f]{8})', l)
        if m:
            fn = m.group(1).lower()
            if fn in target_vas:
                for j in range(i+1, min(len(lines), i+300)):
                    if lines[j].startswith('; FUNCTION'): break
                    rm = re.match(r'^[0-9a-f]{8}\s+[0-9a-f]+\s+RET(?:\s+(0x[0-9a-f]+))?', lines[j])
                    if rm:
                        pop_bytes = int(rm.group(1), 16) if rm.group(1) else 0
                        fn_rets[int(fn, 16)] = pop_bytes
                        break
    for t in unique_calls:
        if t not in fn_rets:
            fn_rets[t] = 0

    return relocs, calls, fn_rets, raw, rva_to_raw


