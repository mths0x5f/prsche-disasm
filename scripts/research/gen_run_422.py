"""Generate the Run 422 native differential fixture (channel lookup, voice iteration).

The two original bodies are copied onto an executable slab and their four
absolute operands (the channel count 006b49a4 and table pointer 006b4a00, twice
each) are patched to fixture storage, each only after its original value is
checked. Every case runs over the same memory twice, original bytes then the
recovered C++, and compares the post-state bytes and the sequence of results.
next_voice is driven like its real caller: from slot 0xffffffff until it
returns 0, recording every (result, slot) pair.
"""
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
EXP = ROOT / 'local/experiments/v2-audio-channel-voice-422'

FIXTURE_CPP = r"""// Autogenerated by scripts/research/gen_run_422.py
#include "audio_channel_voice_lookup_422.hpp"
#include <windows.h>
#include <cstdint>
#include <cstddef>

extern "C" int _fltused = 0x9876;
#pragma function(memcpy, memset, memcmp)
extern "C" void* memcpy(void* dst, const void* src, size_t n) {
    auto d = static_cast<unsigned char*>(dst); auto s = static_cast<const unsigned char*>(src);
    for (size_t i = 0; i < n; ++i) d[i] = s[i];
    return dst;
}
extern "C" void* memset(void* dst, int v, size_t n) {
    auto d = static_cast<unsigned char*>(dst);
    for (size_t i = 0; i < n; ++i) d[i] = static_cast<unsigned char>(v);
    return dst;
}
extern "C" int memcmp(const void* a, const void* b, size_t n) {
    auto p = static_cast<const unsigned char*>(a); auto q = static_cast<const unsigned char*>(b);
    for (size_t i = 0; i < n; ++i) if (p[i] != q[i]) return p[i] < q[i] ? -1 : 1;
    return 0;
}
extern "C" void __cdecl _chkstk() {}

using U = std::uint32_t;
using porsche::AudioChannelRecord_422;

namespace porsche {
std::int16_t audio_backend_channel_count_006b49a4;
std::uint32_t audio_backend_channels_006b4a00;
}

struct Trace { U count; U a[256]; U b[256]; };
static Trace g_trace, s_orig, s_cpp;
static void rec(U a, U b) { if (g_trace.count < 256) { g_trace.a[g_trace.count] = a; g_trace.b[g_trace.count] = b; ++g_trace.count; } }
static bool same(const Trace& x, const Trace& y) {
    if (x.count != y.count) return false;
    for (U i = 0; i < x.count; ++i) if (x.a[i] != y.a[i] || x.b[i] != y.b[i]) return false;
    return true;
}

// ---------------------------------------------------------------------------
// Slab
// ---------------------------------------------------------------------------
static std::uint8_t* s_slab = nullptr;
enum : U { O_FIND = 0x000, O_NEXT = 0x080 };
static bool s_ok = true;
static void abs32(U body, U off, U expected, const void* target) {
    U* p = reinterpret_cast<U*>(s_slab + body + off);
    if (*p != expected) { s_ok = false; return; }
    *p = reinterpret_cast<U>(target);
}
static bool init_slab() {
    HANDLE f = CreateFileA("../../game/Porsche.exe", GENERIC_READ, FILE_SHARE_READ, NULL, OPEN_EXISTING, 0, NULL);
    if (f == INVALID_HANDLE_VALUE) return false;
    DWORD size = GetFileSize(f, NULL), got = 0;
    auto img = static_cast<std::uint8_t*>(VirtualAlloc(NULL, size, MEM_COMMIT | MEM_RESERVE, PAGE_READWRITE));
    if (!img) { CloseHandle(f); return false; }
    ReadFile(f, img, size, &got, NULL); CloseHandle(f);
    if (got != size) return false;
    s_slab = static_cast<std::uint8_t*>(VirtualAlloc(NULL, 4096, MEM_COMMIT | MEM_RESERVE, PAGE_EXECUTE_READWRITE));
    if (!s_slab) return false;
    memcpy(s_slab + O_FIND, img + (0x00589d20u - 0x00400000u), 79);
    memcpy(s_slab + O_NEXT, img + (0x00590340u - 0x00400000u), 133);
    VirtualFree(img, 0, MEM_RELEASE);
    using namespace porsche;
    abs32(O_FIND, 0x11, 0x006b49a4, &audio_backend_channel_count_006b49a4);
    abs32(O_FIND, 0x33, 0x006b4a00, &audio_backend_channels_006b4a00);
    abs32(O_NEXT, 0x07, 0x006b4a00, &audio_backend_channels_006b4a00);
    abs32(O_NEXT, 0x2d, 0x006b49a4, &audio_backend_channel_count_006b49a4);
    return s_ok;
}

// ---------------------------------------------------------------------------
// Scene
// ---------------------------------------------------------------------------
struct Scene { std::int16_t count; U table; U slot; AudioChannelRecord_422 recs[16]; };
static Scene g_s;
static std::uint8_t s_snap_o[sizeof(Scene)], s_snap_c[sizeof(Scene)];

static void put(int i, std::int32_t handle, std::uint8_t active, std::uint8_t group) {
    g_s.recs[i].handle = handle; g_s.recs[i].active = active; g_s.recs[i].group = group;
}
static void standard_table() {
    memset(&g_s, 0, sizeof(g_s));
    for (int i = 0; i < 16; ++i) memset(&g_s.recs[i], 0x5c, sizeof(AudioChannelRecord_422));
    for (int i = 0; i < 16; ++i) put(i, 0, 0, 0);
    put(0, 0x100, 1, 0);
    put(1, 0x201, 1, 2);
    put(2, 0x302, 0, 2);          // inactive
    put(3, 0x403, 1, 2);
    put(4, -5, 1, 2);             // negative handle: next_voice skips it
    put(5, 0x305, 2, 2);          // active == 2: next_voice skips, find_channel accepts
    put(6, 0x606, 1, 3);
    put(7, 0x707, 1, 2);
    g_s.count = 9;
    g_s.table = reinterpret_cast<U>(g_s.recs);
    g_s.slot = 0;
}
static void load() { porsche::audio_backend_channel_count_006b49a4 = g_s.count; porsche::audio_backend_channels_006b4a00 = g_s.table; }
static void save(std::uint8_t* out) {
    g_s.count = porsche::audio_backend_channel_count_006b49a4; g_s.table = porsche::audio_backend_channels_006b4a00;
    memcpy(out, &g_s, sizeof(Scene));
}

using FindFn = std::int32_t(__cdecl*)(U);
using NextFn = U(__cdecl*)(std::int32_t, U*);
static FindFn s_find; static NextFn s_next;

static void find_case(U handle) { rec(0xf1, static_cast<U>(s_find(handle))); }
static void next_loop(std::int32_t channel, U start) {
    g_s.slot = start;
    for (int i = 0; i < 24; ++i) {
        U r = s_next(channel, &g_s.slot);
        rec(r, g_s.slot);
        if (!r) break;
    }
}
static void next_once(std::int32_t channel, U start) { g_s.slot = start; U r = s_next(channel, &g_s.slot); rec(r, g_s.slot); }

static std::int32_t __cdecl cpp_find(U h) { return porsche::audio_backend_find_channel_00589d20(h); }
static U __cdecl cpp_next(std::int32_t c, U* s) { return porsche::audio_backend_next_voice_00590340(c, s); }

struct Case { const char* name; void (*tweak)(); void (*body)(); };

static void t_none() {}
static void t_count_neg() { g_s.count = -1; }
static void t_count_zero() { g_s.count = 0; }

static void b_find_negative()  { find_case(0x80000000u); }
static void b_find_past_count(){ find_case(0x109u); }
static void b_find_count_neg() { find_case(0x100u); }
static void b_find_inactive()  { find_case(0x302u); }
static void b_find_mismatch()  { find_case(0x101u); }
static void b_find_hit0()      { find_case(0x100u); }
static void b_find_hit5()      { find_case(0x305u); }
static void b_find_high_bits() { find_case(0x7fffff07u); }
static void b_find_hit7()      { find_case(0x707u); }
static void b_find_count_zero(){ find_case(0x100u); }
static void b_next_ungrouped() { next_loop(0, 0xffffffffu); }
static void b_next_group2()    { next_loop(1, 0xffffffffu); }
static void b_next_group3()    { next_loop(6, 0xffffffffu); }
static void b_next_ungrouped_started() { next_once(0, 3); }
static void b_next_at_end()    { next_once(1, 8); }
static void b_next_count_neg() { next_once(1, 0xffffffffu); }
static void b_next_from_middle(){ next_loop(1, 3); }

static Case k_cases[] = {
    {"find negative handle", t_none, b_find_negative},
    {"find index past count", t_none, b_find_past_count},
    {"find with negative count", t_count_neg, b_find_count_neg},
    {"find inactive record", t_none, b_find_inactive},
    {"find handle mismatch", t_none, b_find_mismatch},
    {"find hit index 0", t_none, b_find_hit0},
    {"find hit with active 2", t_none, b_find_hit5},
    {"find high bits mismatch", t_none, b_find_high_bits},
    {"find hit index 7", t_none, b_find_hit7},
    {"find with zero count", t_count_zero, b_find_count_zero},
    {"next ungrouped channel", t_none, b_next_ungrouped},
    {"next group 2 full walk", t_none, b_next_group2},
    {"next group 3 full walk", t_none, b_next_group3},
    {"next ungrouped already started", t_none, b_next_ungrouped_started},
    {"next grouped at end", t_none, b_next_at_end},
    {"next grouped negative count", t_count_neg, b_next_count_neg},
    {"next group 2 from middle", t_none, b_next_from_middle},
};

static bool run_case(const Case& c) {
    standard_table(); c.tweak(); load();
    g_trace.count = 0; s_find = reinterpret_cast<FindFn>(s_slab + O_FIND); s_next = reinterpret_cast<NextFn>(s_slab + O_NEXT);
    c.body(); s_orig = g_trace; save(s_snap_o);

    standard_table(); c.tweak(); load();
    g_trace.count = 0; s_find = cpp_find; s_next = cpp_next;
    c.body(); s_cpp = g_trace; save(s_snap_c);

    return memcmp(s_snap_o, s_snap_c, sizeof(Scene)) == 0 && same(s_orig, s_cpp);
}

static void out(const char* s) { DWORD w; WriteFile(GetStdHandle(STD_OUTPUT_HANDLE), s, lstrlenA(s), &w, NULL); }

extern "C" void entry() {
    char buf[160];
    if (!init_slab()) { out("init_slab failed (patch offset check)\n"); ExitProcess(1); }
    int total = static_cast<int>(sizeof(k_cases) / sizeof(k_cases[0])), passed = 0;
    for (int i = 0; i < total; ++i) {
        bool ok = run_case(k_cases[i]); passed += ok;
        wsprintfA(buf, "TC %d %s %s\n", i + 1, ok ? "OK" : "FAILED", k_cases[i].name); out(buf);
    }
    wsprintfA(buf, "passed %d of %d\n", passed, total); out(buf);
    ExitProcess(passed == total ? 0 : 2);
}
"""


def main():
    EXP.mkdir(parents=True, exist_ok=True)
    path = EXP / 'audio_channel_voice_fixture.cpp'
    path.write_bytes(FIXTURE_CPP.replace('\r\n', '\n').encode('utf-8'))
    print(f'Generated {path}')


if __name__ == '__main__':
    main()
