"""Generate the Run 423 native differential fixture (input _getstate, every mode).

Four original bodies go onto an executable slab: 00532e10 (_getstate) and the
poll/read chain it calls for mode 6, 0056fce0 -> 0056fd00 / 0056fd30, linked
original-to-original. The mode table (0x00532f38, 8 entries) and the device-type
table (0x00532f58, 4 entries) are copied out of the image and relocated to the
slab. The three .rdata strings the original passes are copied byte for byte, so
the diagnostic hook can compare message *content* between the original and the
recovered C++, which uses its own literals.

Shared hooks on both sides: the DirectInput vtable (poll, acquire, get_state),
input_caps_0056fdb0, input_property_mode8_0056fff0 and the diagnostic handler,
which the original reaches through the same pointer variable the C++ calls.
Each case runs twice over the same memory and passes only when the post-state
bytes, the call trace and the return value are identical.

Negative and >= 32 indices are not exercised: the original reads outside the
slot array there, which is exactly why the recovery keeps them as boundaries.
"""
