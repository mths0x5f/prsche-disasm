"""Generate the Run 425 native differential fixture (voice stop and its tree).

The four original bodies go onto an executable slab and stay linked
original-to-original: 0058a8b0 calls the slab copies of 00597010 and 00589c00,
and 00597010 calls the slab copy of 0058ac30. Every absolute operand is patched
to fixture storage only after its original value is checked.

The channel table is preceded by a guard record, so the index -1 access in
00589c00 lands on known memory and is compared like everything else. The voice
stop callback is a shared hook that can rewrite the voice flags, to prove the
flags are read after the call.
"""
